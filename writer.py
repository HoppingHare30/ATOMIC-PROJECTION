"""
File exporters for atomic configurations and visualization plots.

Supports CSV, XYZ, JSON, PNG, and SVG output formats.
"""
from __future__ import annotations

import csv
from fractions import Fraction
import json
from pathlib import Path
from typing import Any
import numpy as np


class CustomJSONEncoder(json.JSONEncoder):
    """JSON encoder handling NumPy scalar/array types and Fraction objects."""

    def default(self, obj: Any) -> Any:
        if isinstance(obj, (np.integer, np.int64, np.int32)):
            return int(obj)
        elif isinstance(obj, (np.floating, np.float64, np.float32)):
            return float(obj)
        elif isinstance(obj, np.ndarray):
            return obj.tolist()
        elif isinstance(obj, Fraction):
            return {"numerator": obj.numerator, "denominator": obj.denominator, "float": float(obj)}
        return super().default(obj)


def export_csv(
    filename: str | Path,
    positions: np.ndarray,
    layer_indices: list[int] | np.ndarray,
    labels: list[str] | None = None,
    extra_cols: dict[str, list[Any] | np.ndarray] | None = None,
) -> None:
    """
    Export atomic coordinates and layer attributes to CSV format.

    Args:
        filename: Destination path.
        positions: Nx3 array of atomic coordinates (units of a).
        layer_indices: Sequence of N integer layer indices.
        labels: Optional sequence of N stacking label strings ('A', 'B', etc.).
        extra_cols: Optional dict mapping column headers to sequences of length N.
    """
    pos = np.asarray(positions, dtype=np.float64)
    n_atoms = len(pos)
    l_indices = list(layer_indices)

    if len(l_indices) != n_atoms:
        raise ValueError(f"Length mismatch: {n_atoms} positions vs {len(l_indices)} layer indices.")

    fieldnames = ["x", "y", "z", "layer_index"]
    if labels is not None:
        fieldnames.append("stacking_label")
    if extra_cols is not None:
        for col_name in extra_cols.keys():
            if col_name not in fieldnames:
                fieldnames.append(col_name)

    path = Path(filename)
    path.parent.mkdir(parents=True, exist_ok=True)

    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for i in range(n_atoms):
            row: dict[str, Any] = {
                "x": f"{pos[i, 0]:.12f}",
                "y": f"{pos[i, 1]:.12f}",
                "z": f"{pos[i, 2]:.12f}",
                "layer_index": int(l_indices[i]),
            }
            if labels is not None:
                row["stacking_label"] = str(labels[i])
            if extra_cols is not None:
                for k, col_vals in extra_cols.items():
                    val = col_vals[i]
                    if isinstance(val, (float, np.floating)):
                        row[k] = f"{float(val):.12f}"
                    else:
                        row[k] = val
            writer.writerow(row)


def export_xyz(
    filename: str | Path,
    positions: np.ndarray,
    species: list[str] | str = "X",
    comment: str = "Generated by Lattice Generator",
) -> None:
    """
    Export atomic coordinates to standard XYZ molecular format.

    Line 1: Atom count N
    Line 2: Comment line
    Lines 3..N+2: <Element> <x> <y> <z>

    Args:
        filename: Destination path.
        positions: Nx3 array of atomic coordinates (units of a).
        species: String element symbol or sequence of N element symbols.
        comment: Metadata comment for header line.
    """
    pos = np.asarray(positions, dtype=np.float64)
    n_atoms = len(pos)

    if isinstance(species, str):
        species_list = [species] * n_atoms
    else:
        species_list = list(species)

    if len(species_list) != n_atoms:
        raise ValueError(f"Species length {len(species_list)} != atom count {n_atoms}")

    path = Path(filename)
    path.parent.mkdir(parents=True, exist_ok=True)

    with open(path, "w", encoding="utf-8") as f:
        f.write(f"{n_atoms}\n")
        f.write(f"{comment.strip()}\n")
        for i in range(n_atoms):
            sym = species_list[i]
            x, y, z = pos[i, 0], pos[i, 1], pos[i, 2]
            f.write(f"{sym} {x:.12f} {y:.12f} {z:.12f}\n")


def export_json(
    filename: str | Path,
    data: dict[str, Any],
) -> None:
    """
    Export calculation metadata and geometry data to JSON file.

    Args:
        filename: Destination path.
        data: Dictionary of serializable data and numpy arrays.
    """
    path = Path(filename)
    path.parent.mkdir(parents=True, exist_ok=True)

    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, cls=CustomJSONEncoder, indent=2)


def export_image(
    fig: Any,
    filename: str | Path,
    dpi: int = 300,
) -> None:
    """
    Export Matplotlib figure to PNG or SVG raster/vector image format.

    Args:
        fig: Matplotlib Figure instance.
        filename: Destination file ending in .png or .svg.
        dpi: Dots per inch for raster export (default: 300).
    """
    path = Path(filename)
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(str(path), dpi=dpi, bbox_inches="tight")
